export function detectSystem(rulesText = '') {
  const t = rulesText.toLowerCase();
  if (t.includes('2d6') || t.includes('2к6')) return '2d6';
  if (t.includes('d100') || t.includes('d%')) return 'd100';
  return 'd20';
}
