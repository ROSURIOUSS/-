/** Арка мира: копия, чтобы игра не правила каталог. */
export function arcForWorld(world) {
  const src = world?.arc?.steps?.length ? world.arc : GENERIC_ARC;
  return {
    title: String(src.title || GENERIC_ARC.title).slice(0, 60),
    steps: src.steps.slice(0, 6).map((s) => String(s).slice(0, 120))
  };
}

