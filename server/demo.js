function successLine(margin) {
  if (margin >= 8) return 'Всё складывается даже лучше, чем ты рассчитывал, — и это само по себе настораживает.';
  if (margin >= 0) return 'Получается, но не бесплатно: приходится потратить больше, чем хотелось.';
  return 'Что-то идёт не так с самого начала.';
}

function failureLine(margin) {
  if (margin <= -8) return 'Всё рушится сразу и целиком. Мир не смягчает удар.';
  return 'Не выходит. Мир отвечает холодно и быстро.';
}

