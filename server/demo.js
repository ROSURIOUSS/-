function npcCameo(state) {
  const npcs = state.memory?.npcs || [];
  if (!npcs.length) return '';
  const npc = pick(npcs.slice(-5));
  if (!npc?.name) return '';
  const lines = npc.attitude < 0
    ? [`${npc.name} смотрит на тебя так, будто уже решил, чем всё закончится.`]
    : npc.attitude > 0
      ? [`${npc.name} где-то рядом — достаточно близко, чтобы вмешаться, и достаточно далеко, чтобы не спешить.`]
      : [`${npc.name} не вмешивается. Пока.`];
  return pick(lines);
}

export function demoOpening(state) {
  const w = state.world;
  const sense = pick(SENSES[w.title] || FALLBACK_SENSES);
  const openLine = OPEN_LINES[w.title] ? `${OPEN_LINES[w.title]}\n\n` : '';
  const narration =
    `${sense}\n\n${openLine}${w.start}\n\n` +
    'Ты чувствуешь, как время идёт дальше без твоего разрешения. Кто-то рядом уже принял решение за тебя — остаётся понять, какое.\n\n' +
    'Выбор всегда есть. Цена — тоже.';
  const options = w.opening?.length
    ? w.opening
    : ['Осмотреться и понять, что здесь не так', 'Заговорить с первым, кто не спрятался', 'Уйти, пока есть возможность'];
  return {
    narration,
    options,
    deltas: { location: w.place || w.title, time: 'начало', tension: 1, energy: 0 },
    facts: [{ text: `${state.hero.name} входит в мир «${w.title}»: ${w.start.slice(0, 140)}`, importance: 2, pinned: false }],
    npcs: [],
    dead: false,
    demo: true
  };
}

export function demoTurn(state, { action, roll }) {
  const w = state.world;
  const sense = pick(SENSES[w.title] || FALLBACK_SENSES);
  const resting = /(отдых|сплю|сон|привал|перевяз|сижу|жду|дышу|успока|перекус|ем |пью)/i.test(action);
  const ok = !roll || roll.success;
  const verdict = resting
    ? pick(REST_LINES)
    : roll
      ? ok
        ? successLine(roll.margin)
        : failureLine(roll.margin)
      : 'Ты действуешь без спешки, и мир пока не мешает.';
  const outcome = resting
    ? pick(['Силы возвращаются частично — ровно настолько, чтобы идти дальше.', 'Тело благодарно. Мир — нет: он не любит пауз.'])
    : ok
      ? pick(WINS)
      : pick(FAILS);
  const cameo = npcCameo(state);

  const narration =
    `${sense}\n\nТы делаешь то, что решил: «${action.slice(0, 120)}». ${verdict}\n\n${outcome}\n\n` +
    (cameo ? `${cameo}\n\n` : '') +
    pick(TAILS);

  const deltas = resting
    ? { hp: 0, energy: 8, tension: Math.max(0, (state.scene.tension || 1) - 1), location: state.scene.location, time: state.scene.time }
    : ok
      ? {
          hp: roll?.fumble ? -2 : 0,
          energy: -1,
          tension: Math.min(5, (state.scene.tension || 1) + (roll ? 0 : 1)),
          location: state.scene.location
        }
      : {
          hp: roll?.fumble ? -4 : -1,
          energy: -2,
          tension: Math.min(5, (state.scene.tension || 1) + 1),
          location: state.scene.location
        };

  const fact = resting
    ? { text: `${state.hero.name} сделал передышку в «${state.scene.location}» на ходу ${state.scene.turn}.`, importance: 1, pinned: false }
    : { text: `Ход ${state.scene.turn}: «${action.slice(0, 100)}» — ${roll ? roll.verdict : 'без броска'}.`, importance: 1, pinned: false };

  return {
    narration,
    options: ok
      ? ['Развить преимущество, пока оно есть', 'Отступить и обдумать увиденное', 'Пойти на риск и ускорить события']
      : ['Отступить и перевязать раны', 'Попробовать другой путь к той же цели', 'Признать ошибку и заплатить за неё'],
    deltas,
    facts: [fact],
    npcs: [],
    dead: false,
    demo: true
  };
}

